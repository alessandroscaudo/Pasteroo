import AppKit

/// Polls the general pasteboard's changeCount and records new text clippings.
@MainActor
final class ClipboardMonitor {
    private let store: ClipStore
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Markers from nspasteboard.org that apps use to flag secrets and throwaway content.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    /// False when macOS (15.4+) asks the user before each programmatic read of the pasteboard,
    /// i.e. Pasteroo is not set to Allow in Privacy & Security › Paste from Other Apps.
    /// Changes there apply after Pasteroo restarts.
    static var canReadFreely: Bool {
        guard #available(macOS 15.4, *) else { return true }
        return NSPasteboard.general.accessBehavior == .alwaysAllow
    }

    init(store: ClipStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    /// Writes a clipping back to the pasteboard without re-recording it.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard Prefs.bool(Prefs.recordHistory) else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication
        if let id = source?.bundleIdentifier, Prefs.ignored.contains(where: { $0.bundleID == id }) {
            return
        }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        store.add(text, source: source)
    }
}
